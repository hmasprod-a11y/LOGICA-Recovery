CREATE TABLE IF NOT EXISTS hanouty_stock_issue_history (
    ISSUE_ID VARCHAR(255) NOT NULL,
    ARTICLE_ID VARCHAR(255) NOT NULL,
    ACTOR VARCHAR(255) NOT NULL,
    REASON TEXT NOT NULL,
    CODE TEXT NOT NULL,
    ARTICLE TEXT NOT NULL,
    QUANTITY DECIMAL(48,18) NOT NULL,
    STOCK_BEFORE DECIMAL(48,18) NOT NULL,
    STOCK_AFTER DECIMAL(48,18) NOT NULL,
    VALIDATED_UTC DATETIME(6) NOT NULL,
    PRIMARY KEY (ISSUE_ID, ARTICLE_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
